const fs = require('node:fs');
const path = require('node:path');
const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const { launch, fixture } = require('./tienda-fixture-002.cjs');
let browser;
before(async () => { browser = await launch(); });
after(async () => { await browser?.close(); });
test('003/T07 CP09: aceptar la confirmación vacía la selección y guarda el estado vacío', async () => fixture(browser, async page => {
  await page.locator('.btn-add-cart[data-id="1"]').click();
  const event = page.waitForEvent('dialog');
  const action = page.locator('#clear-cart-btn').click();
  const dialog = await event;
  assert.equal(dialog.type(), 'confirm');
  assert.equal(dialog.message(), '¿Vaciar el carrito?');
  await dialog.accept();
  await action;
  assert.equal(await page.locator('.cart-item-row').count(), 0);
  assert.equal(await page.locator('#cart-count').textContent(), '0');
  assert.equal(await page.locator('#cart-total-price').textContent(), '$0');
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('wolf_cart'))), []);
  const dir = process.env.WOLF_CART_EVIDENCE || path.join(__dirname, 'evidencias/003-carrito-whatsapp');
  fs.mkdirSync(dir, { recursive: true });
  await page.locator('.cart-content').screenshot({ path: path.join(dir, 'carrito-vaciado.png'), animations: 'disabled' });
}));
test('003/T07 CP10: cancelar la confirmación conserva productos, cantidades y almacenamiento', async () => fixture(browser, async page => {
  await page.locator('.btn-add-cart[data-id="1"]').click();
  await page.locator('.btn-plus[data-id="1"]').click();
  const saved = await page.evaluate(() => localStorage.getItem('wolf_cart'));
  const event = page.waitForEvent('dialog');
  const action = page.locator('#clear-cart-btn').click();
  const dialog = await event;
  assert.equal(dialog.type(), 'confirm');
  assert.equal(dialog.message(), '¿Vaciar el carrito?');
  await dialog.dismiss();
  await action;
  assert.equal(await page.locator('.cart-item-details strong').textContent(), 'Notebook Alfa');
  assert.equal(await page.locator('.cart-qty-num').textContent(), '2');
  assert.equal(await page.locator('#cart-total-price').textContent(), '$200');
  assert.equal(await page.evaluate(() => localStorage.getItem('wolf_cart')), saved);
}));
test('003/T07: vaciar cuando ya está vacío no abre diálogo ni modifica el almacenamiento', async () => fixture(browser, async page => {
  let dialogs = 0;
  page.on('dialog', async dialog => { dialogs++; await dialog.dismiss(); });
  const saved = await page.evaluate(() => localStorage.getItem('wolf_cart'));
  await page.locator('#open-cart-btn').click();
  await page.locator('#clear-cart-btn').click();
  assert.equal(dialogs, 0);
  assert.equal(await page.evaluate(() => localStorage.getItem('wolf_cart')), saved);
}));
